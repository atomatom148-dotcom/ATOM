def test_effective_n_ips_and_metric_specific_sequences():
    assert effective_n([1,2])[0] == 2
    assert effective_n([1,1,1])[0] == 3
    assert "SERIAL_DEPENDENCE_UNIDENTIFIABLE" in effective_n([1,1,1])[1]
    dependent=[0,0,1,1,2,2,3,3,4,4]
    assert 1 <= effective_n(dependent)[0] < len(dependent)
    assert effective_n([0,1,0,1,0,1])[0] <= 6


def test_maturity_requires_both_effective_n_and_interval_width():
    evidence=[]
    for i in range(385):
        f=forecast("30S",i,1.0); evidence.append((f,outcome(f,1.0)))
    state=build_accuracy_state(symbol="COIN",state_as_of=NOW+timedelta(days=1),
                               cohorts=cohorts(),evidence=evidence)
    mature=state.horizon_states[0]
    assert mature.directional_effective_n == 385
    assert mature.jeffreys_interval_width <= .10 and mature.status == "MATURE"
    provisional=build_accuracy_state(symbol="COIN",state_as_of=NOW+timedelta(days=1),
        cohorts=cohorts(),evidence=evidence[:384]).horizon_states[0]
    assert provisional.status == "PROVISIONAL"


class Cursor:
    def __init__(self, rows): self.rows=rows; self.sql=[]
    def execute(self,sql,args): self.sql.append((sql,args))
    def fetchall(self): return self.rows.pop(0)
class Connection:
    def __init__(self,rows): self.cursor_value=Cursor(rows)
    def cursor(self): return self.cursor_value


def test_store_idempotence_insert_and_same_time_conflict():
    empty=build_accuracy_state(symbol="COIN",state_as_of=NOW,cohorts=cohorts(),evidence=[])
    con=Connection([[],[]]); store=AccuracyStateStore(con)
    assert store.insert(empty,NOW)=="INSERT"
    assert "INSERT INTO atom_v9_v4_states" in con.cursor_value.sql[-1][0]
    con=Connection([[(empty.state_hash,)]]); assert AccuracyStateStore(con).insert(empty,NOW)=="IDEMPOTENT"
    con=Connection([[('a',{},NOW),('b',{},NOW)]])
    assert AccuracyStateStore(con).latest_json(symbol="COIN",cohort_id="x",requested_cutoff=NOW)[1]=="STATE_CONFLICT"
